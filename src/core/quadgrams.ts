/**
 * The level of every quadgram, indexed by its letters as a base-26 number, A as 0.
 *
 * @returns {Uint8Array} 26^4 levels; missing quadgrams get `MISSING_LEVEL`.
 */
export function quadgramLevels(): Uint8Array {
  const levels = missingLevels()
  for (const line of quadgrams.trim().split('\n')) {
    const [level, letters] = line.split(' ')
    for (let start = 0; start < letters!.length; start += 4) {
      levels[quadgramIndex(letters!, start)] = Number(level)
    }
  }
  return levels
}

/**
 * Levels of quadgrams the table lacks: worse for rare letters, never better than the rarest kept.
 *
 * @returns {Uint8Array} 26^4 levels.
 */
function missingLevels(): Uint8Array {
  const logs = Array.from({ length: 26 }, (_, code) =>
    languageTables('en').letterLogs.get(String.fromCodePoint(65 + code))!,
  )
  const common = Math.max(...logs) * 4
  const levels = new Uint8Array(26 ** 4)
  for (let index = 0; index < levels.length; index++) {
    let log = 0
    let rest = index
    for (let letter = 0; letter < 4; letter++) {
      log += logs[rest % 26]!
      rest = Math.floor(rest / 26)
    }
    levels[index] = MISSING_LEVEL + Math.round((common - log) / QUADGRAM_STEP / BACKOFF)
  }
  return levels
}

/**
 * The index of the four letters at `start` in `quadgramLevels`.
 *
 * @param letters - Uppercase A-Z letters.
 * @param start - Where the quadgram begins.
 * @returns {number} Its letters as a base-26 number.
 */
function quadgramIndex(letters: string, start: number): number {
  let index = 0
  for (let offset = 0; offset < 4; offset++) {
    index = index * 26 + letters.codePointAt(start + offset)! - 65
  }
  return index
}

/**
 * Sum of the levels of every quadgram in a run of letters, lower reading more like English.
 *
 * @param levels - The table from `quadgramLevels`.
 * @param codes - Letters as 0 to 25.
 * @param length - How many of `codes` to score, from the start.
 * @returns {number} The sum; zero below four letters.
 */
export function quadgramLevelSum(
  levels: ArrayLike<number>,
  codes: ArrayLike<number>,
  length: number = codes.length,
): number {
  let sum = 0
  for (let index = 0; index + 3 < length; index++) sum += quadgramLevel(levels, codes, index)
  return sum
}

/**
 * The level of the quadgram that starts at `at` in a run of letters.
 *
 * @param levels - The table from `quadgramLevels`.
 * @param codes - Letters as 0 to 25, at least four from `at`.
 * @param at - Where the quadgram starts.
 * @returns {number} Its level.
 */
export function quadgramLevel(
  levels: ArrayLike<number>,
  codes: ArrayLike<number>,
  at: number,
): number {
  return levels[((codes[at]! * 26 + codes[at + 1]!) * 26 + codes[at + 2]!) * 26 + codes[at + 3]!]!
}

/**
 * Mean natural-log probability of one quadgram under the table when its letters are random.
 *
 * @param levels - The table from `quadgramLevels`.
 * @returns {number} The mean over every quadgram, each counted once.
 */
export function randomQuadgramFit(levels: ArrayLike<number>): number {
  let sum = 0
  for (let index = 0; index < levels.length; index++) sum += levels[index]!
  return (-sum * QUADGRAM_STEP) / levels.length
}
